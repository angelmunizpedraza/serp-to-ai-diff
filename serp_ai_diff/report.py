"""Markdown and CSV output."""

from __future__ import annotations

import csv
import io
from typing import Dict, List

from .compare import KeywordDiff


def _pct(x) -> str:
    return "—" if x is None else f"{x*100:.0f} %"


def markdown(agg: Dict, diffs: List[KeywordDiff], my_domain: str | None) -> str:
    L: List[str] = []
    L.append(f"# Google vs {agg['ai_engine']} — citation overlap study")
    L.append("")
    L.append(f"{agg['keywords']} keywords · avg URL overlap (Jaccard) **{_pct(agg['avg_url_jaccard'])}** · avg domain overlap **{_pct(agg['avg_domain_jaccard'])}** · keywords with any shared domain **{_pct(agg['pct_keywords_with_any_overlap'])}**")
    L.append("")
    L.append("## Does ranking in Google get you cited?")
    L.append("")
    L.append("| Google rank | Cited by AI |")
    L.append("|---:|---:|")
    for i, r in enumerate(agg["cited_rate_by_rank"], 1):
        L.append(f"| {i} | {_pct(r)} |")
    L.append("")
    L.append("## Domains the AI trusts that Google does not rank (top 10)")
    L.append("")
    L.append("| Domain | Keywords |")
    L.append("|---|---:|")
    for dom, c in agg["top_ai_only_domains"]:
        L.append(f"| {dom} | {c} |")
    L.append("")
    L.append("## Domains Google ranks that the AI never cites")
    L.append("")
    L.append("| Domain | Keywords |")
    L.append("|---|---:|")
    for dom, c in agg["top_google_only_domains"]:
        L.append(f"| {dom} | {c} |")
    L.append("")
    if my_domain:
        m = agg["my_domain"]
        L.append(f"## Your domain: {my_domain}")
        L.append("")
        L.append(f"- Ranking in Google top 10 for **{m['keywords_ranking_top10']}** keywords; cited by the AI for **{m['keywords_cited']}**.")
        if m["ranking_but_not_cited"]:
            L.append(f"- **Ranking but NOT cited** ({len(m['ranking_but_not_cited'])}) — your GEO backlog: " + "; ".join(f'"{k}"' for k in m["ranking_but_not_cited"]))
        if m["cited_but_not_ranking"]:
            L.append(f"- Cited but not in Google top 10 ({len(m['cited_but_not_ranking'])}): " + "; ".join(f'"{k}"' for k in m["cited_but_not_ranking"]))
        L.append("")
    L.append("## Per keyword")
    L.append("")
    L.append("| Keyword | URL Jaccard | Domain Jaccard | First cited Google rank | Shared domains |")
    L.append("|---|---:|---:|---:|---|")
    for d in diffs:
        L.append(f"| {d.keyword} | {_pct(d.url_jaccard)} | {_pct(d.domain_jaccard)} | {d.first_cited_google_rank or '—'} | {', '.join(d.shared_domains) or '—'} |")
    L.append("")
    L.append("_Generated by serp-to-ai-diff._")
    return "\n".join(L)


def csv_text(diffs: List[KeywordDiff]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["keyword", "ai_engine", "google_rank", "url", "domain", "cited_by_ai"])
    for d in diffs:
        cited = set(d.ai_urls)
        cited_dom = {u.split("/")[2] for u in d.ai_urls}
        for i, u in enumerate(d.google_urls, 1):
            dom = u.split("/")[2]
            w.writerow([d.keyword, d.ai_engine, i, u, dom, int(u in cited or dom in cited_dom)])
    return buf.getvalue()
